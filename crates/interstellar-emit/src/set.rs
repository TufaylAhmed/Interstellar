use interstellar_ir::{
    AddressValue, NatType, PolicyDocument, RuleAction, ServiceValue,
};

pub fn emit_set_commands(doc: &PolicyDocument) -> String {
    let mut lines = Vec::new();
    lines.push("# PAN-OS set commands generated by Interstellar".into());
    lines.push(format!("# source vendor: {}", doc.vendor.as_str()));

    for a in &doc.addresses {
        match &a.value {
            AddressValue::IpNetmask { value } => {
                lines.push(format!(
                    "set address {} ip-netmask {}",
                    a.name, value
                ));
            }
            AddressValue::IpRange { from, to } => {
                lines.push(format!(
                    "set address {} ip-range {}-{}",
                    a.name, from, to
                ));
            }
            AddressValue::Fqdn { value } => {
                lines.push(format!("set address {} fqdn {}", a.name, value));
            }
            AddressValue::IpWildcard { ip, mask } => {
                lines.push(format!(
                    "set address {} ip-wildcard {}/{}",
                    a.name, ip, mask
                ));
            }
        }
        if let Some(d) = &a.description {
            lines.push(format!("set address {} description \"{}\"", a.name, d));
        }
    }

    for g in &doc.address_groups {
        for m in &g.members {
            lines.push(format!(
                "set address-group {} static {}",
                g.name, m
            ));
        }
    }

    for s in &doc.services {
        match &s.value {
            ServiceValue::Tcp { port } => {
                lines.push(format!(
                    "set service {} protocol tcp port {}",
                    s.name, port
                ));
            }
            ServiceValue::Udp { port } => {
                lines.push(format!(
                    "set service {} protocol udp port {}",
                    s.name, port
                ));
            }
            ServiceValue::TcpUdp { port } => {
                lines.push(format!(
                    "set service {} protocol tcp port {}",
                    s.name, port
                ));
            }
            ServiceValue::Protocol { protocol } => {
                lines.push(format!(
                    "set service {} protocol other protocol-number {}",
                    s.name, protocol
                ));
            }
            ServiceValue::Any => {
                lines.push(format!(
                    "set service {} protocol tcp port 0-65535",
                    s.name
                ));
            }
        }
    }

    for g in &doc.service_groups {
        for m in &g.members {
            lines.push(format!(
                "set service-group {} members {}",
                g.name, m
            ));
        }
    }

    for p in &doc.profile_groups {
        if let Some(v) = &p.virus {
            lines.push(format!(
                "set profile-group {} virus {}",
                p.name, v
            ));
        }
        if let Some(v) = &p.vulnerability {
            lines.push(format!(
                "set profile-group {} vulnerability {}",
                p.name, v
            ));
        }
        if let Some(v) = &p.url_filtering {
            lines.push(format!(
                "set profile-group {} url-filtering {}",
                p.name, v
            ));
        }
    }

    for r in &doc.security_rules {
        let base = format!("set rulebase security rules {}", r.name);
        for z in &r.from_zones {
            lines.push(format!("{base} from {z}"));
        }
        for z in &r.to_zones {
            lines.push(format!("{base} to {z}"));
        }
        for s in &r.source {
            lines.push(format!("{base} source {s}"));
        }
        for d in &r.destination {
            lines.push(format!("{base} destination {d}"));
        }
        for a in &r.application {
            lines.push(format!("{base} application {a}"));
        }
        for s in &r.service {
            lines.push(format!("{base} service {s}"));
        }
        lines.push(format!("{base} action {}", action_str(r.action)));
        if r.disabled {
            lines.push(format!("{base} disabled yes"));
        }
        if let Some(pg) = &r.profile_group {
            lines.push(format!("{base} profile-setting group {pg}"));
        }
    }

    for n in &doc.nat_rules {
        let base = format!("set rulebase nat rules {}", n.name);
        for z in &n.from_zones {
            lines.push(format!("{base} from {z}"));
        }
        for z in &n.to_zones {
            lines.push(format!("{base} to {z}"));
        }
        for s in &n.source {
            lines.push(format!("{base} source {s}"));
        }
        for d in &n.destination {
            lines.push(format!("{base} destination {d}"));
        }
        match n.nat_type {
            NatType::Source | NatType::Static => {
                if let Some(ts) = &n.translated_source {
                    if n.nat_type == NatType::Static {
                        lines.push(format!(
                            "{base} source-translation static-ip translated-address {ts}"
                        ));
                    } else {
                        lines.push(format!(
                            "{base} source-translation dynamic-ip-and-port translated-address {ts}"
                        ));
                    }
                }
            }
            NatType::Destination => {
                if let Some(td) = &n.translated_destination {
                    lines.push(format!(
                        "{base} destination-translation translated-address {td}"
                    ));
                }
            }
        }
    }

    for g in &doc.ike_gateways {
        lines.push(format!(
            "set network ike gateway {} peer-address ip {}",
            g.name, g.peer_ip
        ));
        lines.push(format!(
            "set network ike gateway {} protocol version {}",
            g.name, g.ike_version
        ));
    }

    for t in &doc.ipsec_tunnels {
        lines.push(format!(
            "set network tunnel ipsec {} auto-key ike-gateway {}",
            t.name, t.ike_gateway
        ));
    }

    lines.join("\n") + "\n"
}

fn action_str(a: RuleAction) -> &'static str {
    a.as_panos()
}
